let totalScanned = 0;
let spamCount = 0;

function runAnalysis() {
    const input = document.getElementById('inputText').value.trim();
    const resultPanel = document.getElementById('resultPanel');
    const statusBadge = document.getElementById('statusBadge');
    const progressFill = document.getElementById('progressFill');
    const scorePercent = document.getElementById('scorePercent');
    const issueDetails = document.getElementById('issueDetails');

    if (!input) {
        alert('Vui lòng nhập văn bản hoặc URL để kiểm tra!');
        return;
    }

    totalScanned++;
    issueDetails.innerHTML = '';
    let score = 0;
    let issues = [];

    // 1. Kiểm tra Comment/Link Spam Keywords
    const spamKeywords = ['casino', 'vảy ốc', 'cờ bạc', 'cheap backlink', 'buy followers', 'seo package', 'bet88', 'kèo nhà cái'];
    spamKeywords.forEach(kw => {
        if (input.toLowerCase().includes(kw)) {
            score += 30;
            issues.push(`Phát hiện từ khóa vi phạm chính sách Spam (Keyword: "${kw}")`);
        }
    });

    // 2. Phân tích mật độ URL (Link Spam)
    const urls = input.match(/https?:\/\/[^\s]+/g) || [];
    if (urls.length > 2) {
        score += 35;
        issues.push(`Mật độ URL quá cao (${urls.length} liên kết trong bài) - Dấu hiệu Link Spam`);
    }

    // 3. Kiểm tra cấu trúc Doorway Pages (Param Spam)
    if (input.includes('?city=') || input.includes('?location=') || input.includes('target_dir=')) {
        score += 25;
        issues.push('Phát hiện dấu hiệu định dạng URL trang đệm (Doorway Pages)');
    }

    // Gioi han score toi da 100%
    score = Math.min(score, 100);

    // Cập nhật giao diện Kết quả
    resultPanel.classList.remove('hidden');
    scorePercent.innerText = score + '%';
    progressFill.style.width = score + '%';

    if (score >= 40) {
        spamCount++;
        statusBadge.className = 'status-badge danger';
        statusBadge.innerHTML = '<i class="fa-solid fa-triangle-exclamation"></i> CẢNH BÁO: PHÁT HIỆN DẤU HIỆU SEO SPAM!';
        progressFill.style.backgroundColor = '#ef4444';
    } else {
        statusBadge.className = 'status-badge success';
        statusBadge.innerHTML = '<i class="fa-solid fa-circle-check"></i> AN TOÀN: NỘI DUNG / LINK HỢP LỆ';
        progressFill.style.backgroundColor = '#10b981';
        issues.push('Không tìm thấy dấu hiệu vi phạm phổ biến.');
    }

    issues.forEach(iss => {
        const li = document.createElement('li');
        li.innerHTML = `<i class="fa-solid fa-angle-right"></i> ${iss}`;
        issueDetails.appendChild(li);
    });

    // Cập nhật thẻ KPI
    document.getElementById('kpiTotal').innerText = totalScanned;
    document.getElementById('kpiSpam').innerText = spamCount;
    const safetyRate = Math.round(((totalScanned - spamCount) / totalScanned) * 100);
    document.getElementById('kpiSafety').innerText = safetyRate + '%';
}

function clearInput() {
    document.getElementById('inputText').value = '';
    document.getElementById('resultPanel').classList.add('hidden');
}

// Export Disavow File
function exportDisavow() {
    const text = document.getElementById('disavowList').value.trim();
    if (!text) {
        alert('Vui lòng nhập danh sách domain để xuất file disavow.txt');
        return;
    }

    const lines = text.split('\n');
    let fileContent = '# Generated by SEO Shield Topic 18\n# Google Disavow File\n\n';
    lines.forEach(line => {
        if(line.trim()) {
            fileContent += `domain:${line.trim()}\n`;
        }
    });

    const blob = new Blob([fileContent], { type: 'text/plain' });
    const anchor = document.createElement('a');
    anchor.href = URL.createObjectURL(blob);
    anchor.download = 'disavow.txt';
    anchor.click();
}